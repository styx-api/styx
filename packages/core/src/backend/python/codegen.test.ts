describe("Python generation - discriminated unions", () => {
  it("emits @type literal on each variant TypedDict via functional syntax", () => {
    const code = generate(
      seq(namedAlt("source", seq(lit("--file"), path("file")), seq(lit("--url"), str("url")))),
    );
    expect(code).toContain('"@type": typing.Literal["variant_0"]');
    expect(code).toContain('"file": InputPathType');
    expect(code).toContain('"@type": typing.Literal["variant_1"]');
    expect(code).toContain('"url": str');
  });

  it("emits union type alias referencing variant TypedDicts", () => {
    const code = generate(
      seq(namedAlt("source", seq(lit("--file"), path("file")), seq(lit("--url"), str("url")))),
    );
    expect(code).toMatch(/^\w+ = \w+ \| \w+$/m);
  });

  it("uses named variants when alt children have meta names", () => {
    const expr = seq({
      kind: "alternative" as const,
      attrs: {
        alts: [
          { ...seq(lit("--file"), path("file")), meta: { name: "by_file" } },
          { ...seq(lit("--url"), str("url")), meta: { name: "by_url" } },
        ],
      },
      meta: { name: "source" },
    });
    const code = generate(expr);
    expect(code).toContain('"@type": typing.Literal["by_file"]');
    expect(code).toContain('"@type": typing.Literal["by_url"]');
    expect(code).toMatch(/if params\["source"\]\["@type"\] == "by_file":/);
  });

  it("does not emit @type on literal union variant aliases", () => {
    const code = generate(seq(namedAlt("mode", lit("fast"), lit("slow"))));
    expect(code).not.toContain('"@type": typing.Literal["fast"]');
    expect(code).toMatch(/typing\.Literal\["fast"\]\s*\|\s*typing\.Literal\["slow"\]/);
  });

  it("emits correct cargs for each variant branch", () => {
    const code = generate(
      seq(
        lit("cmd"),
        namedAlt("source", seq(lit("--file"), path("file")), seq(lit("--url"), str("url"))),
      ),
      { app: { id: "t" } },
    );
    expect(code).toContain('cargs.append("--file")');
    expect(code).toContain('execution.input_file(params["source"]["file"])');
    expect(code).toContain('cargs.append("--url")');
    expect(code).toContain('params["source"]["url"]');
  });

  // Regression: a mixed union (struct + bare-literal variants, e.g. ants
  // `Interpolation`) cannot dispatch with `params.x["@type"]` because the
  // literal arms aren't dicts. cargs must branch on runtime shape.
  it("emits a runtime-shape branch for mixed (struct + literal) unions", () => {
    const code = generate(
      seq(lit("cmd"), namedAlt("mode", lit("fast"), seq(lit("--full"), str("level")))),
      { app: { id: "t" } },
    );
    expect(code).toContain('if isinstance(params["mode"], dict):');
    expect(code).toContain('if params["mode"]["@type"] == "variant_1":');
    expect(code).toContain('cargs.append(str(params["mode"]))');
  });
});

