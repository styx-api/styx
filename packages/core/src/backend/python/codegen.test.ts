describe("Python generation - cargs building", () => {
  it("appends literal strings", () => {
    const code = generate(seq(lit("tool"), str("input")));
    expect(code).toContain('cargs.append("tool")');
  });

  it("appends string params directly (no str())", () => {
    const code = generate(seq(str("name")));
    expect(code).toContain('cargs.append(params["name"])');
  });

  it("wraps int params with str()", () => {
    const code = generate(seq(int("count")));
    expect(code).toContain('cargs.append(str(params["count"]))');
  });

  it("uses execution.input_file for path params", () => {
    const code = generate(seq(path("infile")));
    expect(code).toContain('cargs.append(execution.input_file(params["infile"]))');
  });

  it("emits is-not-None check for optional params", () => {
    const code = generate(seq(opt(str("name"))));
    expect(code).toContain('if params["name"] is not None:');
  });

  it("emits truthy check for bool flags", () => {
    const code = generate(seq(opt(seq(lit("-v")))));
    expect(code).toMatch(/if params\["\w+"\]:/);
  });

  it("emits for-in loop for list params with correct loop variable", () => {
    const code = generate(seq(rep(int("val"), "vals")));
    // Scope to the cargs function: the validate function also loops over the list.
    const cargs = code.slice(code.indexOf("def cargs("));
    const match = cargs.match(/for (\w+) in params\["vals"\]:/);
    expect(match).toBeTruthy();
    const itemVar = match![1];
    expect(cargs).toContain(`str(${itemVar})`);
  });

  it("emits range() loop for count params", () => {
    const code = generate(seq(rep(seq(lit("-v")), "verbosity")));
    expect(code).toMatch(/for _i\d+ in range\(/);
  });

  it("handles nested optional with flag and value", () => {
    const code = generate(seq(opt(seq(lit("-f"), float("threshold")))));
    expect(code).toContain('if params["threshold"] is not None:');
    expect(code).toContain('cargs.append("-f")');
    expect(code).toContain('cargs.append(str(params["threshold"]))');
  });

  it("handles literal union alternative as str() append", () => {
    const code = generate(seq(alt(lit("fast"), lit("slow"))));
    expect(code).toContain("cargs.append(str(params[");
  });
});

